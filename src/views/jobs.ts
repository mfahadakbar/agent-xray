/**
 * "Give Ray a job": pick the kind of agent you want, and watch that job travel through Ray,
 * part by part, the same way a single message does. Every job has its own story.
 */
export interface Job {
  id: string;
  icon: string;
  name: string;
  does: string;
  /** What somebody asks this agent to do. The story follows this one task. */
  task: string;
  /** Where the task comes in, when it does not come from you (a phone line, for example). */
  from?: Flow['from'];
  story: Beat[];
  /** Paths of the boxes this job leans on most. */
  parts: string[];
}

