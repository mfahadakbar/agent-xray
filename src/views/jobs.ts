export const JOB: Record<string, Job> = Object.fromEntries(JOBS.map((j) => [j.id, j]));

/** A job told as a journey, in the same shape as a message travelling through Ray. */
export function jobFlow(job: Job): Flow {
  return { question: job.task, from: job.from, beats: job.story };
}

/** The boxes a job needs, looked up on the map. Unknown paths are dropped rather than shown broken. */
export function jobParts(job: Job): Flat[] {
  return job.parts.map((p) => ALL.find((f) => f.key === p)).filter((f): f is Flat => !!f);
}

/** The parts of Ray a job's story visits. They stay bright while the rest of Ray goes quiet. */
export function jobOrgans(job: Job): OrganId[] {
  const set = new Set<OrganId>();
  job.story.forEach((b) => b.organ && set.add(b.organ));
  return [...set];
}
